class LoginAttempt(Base):
    __tablename__ = "login_attempts"

    # Integer (not BigInteger) so SQLite autoincrements; still an
    # append-only log table per AGENTS.md. Postgres: INTEGER is fine
    # for login attempts volume in Step 2; revisit if volume grows.
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    email: Mapped[str] = mapped_column(String(320), nullable=False)
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    ip: Mapped[str | None] = mapped_column(String(45), nullable=True)
    user_agent: Mapped[str | None] = mapped_column(Text, nullable=True)
    succeeded: Mapped[bool] = mapped_column(Boolean, nullable=False)
    failure_reason: Mapped[str | None] = mapped_column(String(128), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        Index("login_attempts_email_idx", "email", "created_at"),
        Index("login_attempts_ip_idx", "ip", "created_at"),
    )
